"""Convert tests/payloads/xss.txt into a psql fixture for pgTAP (tests/payloads/xss_payloads.psql).

Usage:  python tools/build_payload_fixture.py [--check]

Payloads containing NUL are skipped: PostgreSQL cannot store NUL in text at all, so such input is
rejected before any CHECK runs. The fixture uses the .psql extension so pg_prove does not run it as a test.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests" / "payloads" / "xss.txt"
TARGET = ROOT / "tests" / "payloads" / "xss_payloads.psql"


def load() -> tuple[str, list[str]]:
    version = ""
    payloads: list[str] = []
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        if line.startswith("# payload-list-version:"):
            version = line.split(":", 1)[1].strip()
        if not line or line.startswith("#"):
            continue
        payloads.append(json.loads(line[5:]) if line.startswith("json:") else line)
    return version, payloads


def sql_literal(value: str) -> str:
    """E'' literal with every non-printable or non-ASCII character escaped."""
    out = []
    for ch in value:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == "'":
            out.append("\\'")
        elif 32 <= code < 127:
            out.append(ch)
        elif code <= 0xFFFF:
            out.append(f"\\u{code:04X}")
        else:
            out.append(f"\\U{code:08X}")
    return "E'" + "".join(out) + "'"


def build() -> str:
    version, payloads = load()
    usable = [p for p in payloads if "\x00" not in p]
    rows = ",\n".join(f"    ({i}, {sql_literal(p)})" for i, p in enumerate(usable, start=1))
    return (
        f"-- GENERATED by tools/build_payload_fixture.py from xss.txt (payload-list-version: {version}).\n"
        f"-- {len(usable)} payloads ({len(payloads) - len(usable)} skipped: contain NUL, which PostgreSQL rejects).\n"
        "CREATE TEMP TABLE test_payloads (id integer PRIMARY KEY, payload text NOT NULL);\n"
        f"INSERT INTO test_payloads (id, payload) VALUES\n{rows};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            print("xss_payloads.psql is stale: run python tools/build_payload_fixture.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
