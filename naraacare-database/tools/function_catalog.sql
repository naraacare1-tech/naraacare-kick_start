-- Generates functions/README.md from a migrated database (catalog = source of truth):
--   psql -X -At -d naraacare_test -f tools/function_catalog.sql > functions/README.md
SELECT string_agg(line, E'\n' ORDER BY ord)
FROM (
    SELECT 0 AS ord, '# Database routines (generated)' AS line
    UNION ALL SELECT 1, ''
    UNION ALL SELECT 2, 'Generated by `tools/function_catalog.sql` from a migrated database; do not edit by hand.'
    UNION ALL SELECT 3, 'Conventions: doc 05 section 7, doc 07 SEC-4.1/4.3. Errors: `22023` invalid input, `42501` not the actor'
    UNION ALL SELECT 4, '(API answers 404), `P0001` business rule with the app code in DETAIL, `40001` retry once.'
    UNION ALL SELECT 5, ''
    UNION ALL SELECT 6, '| Routine | Kind | Owner | Volatility | Callable by | Purpose |'
    UNION ALL SELECT 7, '|---|---|---|---|---|---|'
    UNION ALL
    SELECT
        100 + row_number() OVER (ORDER BY n.nspname, p.proname)::integer,
        format(
            '| `%s` | %s | %s | %s | %s | %s |',
            replace(p.oid::regprocedure::text, '|', '\|'),
            CASE p.prokind WHEN 'p' THEN 'procedure' ELSE CASE WHEN p.prorettype = 'trigger'::regtype THEN 'trigger fn' ELSE 'function' END END
            || CASE WHEN p.prosecdef THEN ', definer' ELSE '' END,
            pg_get_userbyid(p.proowner),
            CASE p.provolatile WHEN 'i' THEN 'immutable' WHEN 's' THEN 'stable' ELSE 'volatile' END,
            coalesce((
                SELECT string_agg(r.rolname, ', ' ORDER BY r.rolname)
                FROM pg_roles AS r
                WHERE r.rolname IN ('app_rw', 'app_worker', 'app_readonly', 'reporting')
                  AND has_function_privilege(r.oid, p.oid, 'EXECUTE')
            ), 'internal'),
            replace(coalesce(obj_description(p.oid, 'pg_proc'), ''), '|', '\|')
        )
    FROM pg_proc AS p
    INNER JOIN pg_namespace AS n ON n.oid = p.pronamespace
    WHERE n.nspname IN (
        'common', 'auth', 'app', 'ref', 'activity', 'nutrition', 'hydration', 'sleep',
        'billing', 'notify', 'privacy', 'audit', 'ops', 'social', 'ai', 'report', 'support'
    )
) AS t;
