"""Build the shared script/markup payload list (doc 07 §4.7) from base vectors.

Usage:  python tools/build_payloads.py            # writes tests/security/payloads/xss.txt
        python tools/build_payloads.py --check    # exits 1 if xss.txt is stale

The output is deterministic so the three repos can carry byte-identical copies.
"""

from __future__ import annotations

import argparse
import html
import json
import sys
import urllib.parse
from pathlib import Path

VERSION = "1.0.0"
ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "tests/security/payloads/base_vectors.txt"
OUT = ROOT / "tests/security/payloads/xss.txt"

FULL_WIDTH = str.maketrans({"<": chr(0xFF1C), ">": chr(0xFF1E)})  # NFKC folds these to <>


def read_base() -> list[str]:
    vectors: list[str] = []
    for raw in BASE.read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.startswith("#"):
            continue
        vectors.append(json.loads(raw[5:]) if raw.startswith("json:") else raw)
    return vectors


def variants(v: str) -> list[str]:
    """Encoded/obfuscated forms. Each still contains a pattern every Safe* type rejects."""
    out = [v]
    if "<" in v or ">" in v or ":" in v or "=" in v:
        out.append(urllib.parse.quote(v, safe=""))  # URL-encoded
        out.append(urllib.parse.quote(urllib.parse.quote(v, safe=""), safe=""))  # double
    if "<" in v or ">" in v:
        out.append(html.escape(v, quote=True))  # named entities
        out.append("".join(f"&#{ord(c)};" if c in "<>" else c for c in v))  # decimal
        out.append("".join(f"&#x{ord(c):x};" if c in "<>" else c for c in v))  # hex
        out.append(v.translate(FULL_WIDTH))  # full-width
        out.append(v.replace("<", "\\u003c").replace(">", "\\u003e"))  # escaped unicode text
        out.append(v.upper())
    return out


def encode_line(p: str) -> str:
    """Plain line if printable and single-line; otherwise a json: line."""
    if p.isprintable() and "\n" not in p and not p.startswith(("#", "json:")) and p.strip() == p:
        return p
    return "json:" + json.dumps(p, ensure_ascii=True)


def build() -> str:
    seen: set[str] = set()
    lines: list[str] = []
    for base in read_base():
        for p in variants(base):
            if p and p not in seen:
                seen.add(p)
                lines.append(encode_line(p))
    header = [
        f"# payload-list-version: {VERSION}",
        "# Shared script/markup payloads (doc 07 §4.7)."
        " GENERATED by naraacare-backend/tools/build_payloads.py.",
        "# Format: one payload per line; `json:` lines hold a JSON string literal;"
        " `#` lines are comments.",
        "# Copies in naraacare-mobile and naraacare-database must be byte-identical"
        " (CI checks the version).",
        f"# count: {len(lines)}",
    ]
    return "\n".join(header + lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("xss.txt is stale: run python tools/build_payloads.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({content.count(chr(10)) - 5} payloads)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
